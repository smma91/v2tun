// Generates THIRD_PARTY_NOTICES.md: every Go module compiled into v2tun (the
// Windows and the Linux build),
// its license (detected from its LICENSE file) and the full license texts.
// Run: node tools/notices.js "<build tags>"
const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const tags = process.argv[2] || "";
const list = (goos, extra) => execSync(`go list -deps -tags "${tags}${extra}" -f "{{with .Module}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}" ./cmd/v2tun`,
  { cwd: root, maxBuffer: 64 << 20, env: { ...process.env, GOOS: goos, GOARCH: "amd64", CGO_ENABLED: "1" } }).toString();
const out = list("windows", "") + "\n" + list("linux", ",webkit2_41");
const mods = new Map();
for (const l of out.split(/\r?\n/)) {
  const [p, v, d] = l.split("|");
  if (p && d && p !== "v2tun") mods.set(p, { v, d });
}
const detect = (t) => {
  if (/GNU GENERAL PUBLIC LICENSE\s+Version 3/i.test(t)) return "GPL-3.0";
  if (/GNU General Public License as published by\s+the Free Software Foundation, either version 3/i.test(t)) return "GPL-3.0-or-later";
  if (/Creative Commons|CC0/i.test(t)) return "CC0-1.0";
  if (/Permission to use, copy, modify,? (and\/or )?(and )?distribute this software/i.test(t)) return "ISC";
  if (/Licensed under the Apache License, Version 2\.0/i.test(t)) return "Apache-2.0";
  if (/GNU LESSER GENERAL PUBLIC LICENSE/i.test(t)) return "LGPL";
  if (/Mozilla Public License,? (Version|v\.) ?2\.0/i.test(t)) return "MPL-2.0";
  if (/Apache License\s+Version 2\.0/i.test(t)) return "Apache-2.0";
  if (/Permission is hereby granted, free of charge/i.test(t)) return "MIT";
  if (/Redistribution and use in source and binary forms/i.test(t)) return /Neither the name/i.test(t) ? "BSD-3-Clause" : "BSD-2-Clause";
  if (/ISC License|Permission to use, copy, modify, and\/or distribute/i.test(t)) return "ISC";
  if (/This is free and unencumbered software/i.test(t)) return "Unlicense";
  return "see license text";
};
const rows = [];
const texts = [];
for (const [p, { v, d }] of [...mods].sort()) {
  const f = fs.readdirSync(d).find((x) => /^(LICEN[CS]E|COPYING)(\.|$)/i.test(x));
  const text = f ? fs.readFileSync(path.join(d, f), "utf8") : "";
  const lic = f ? detect(text) : "UNKNOWN";
  rows.push(`| ${p} | ${v || ""} | ${lic} |`);
  if (text) texts.push(`### ${p}\n\n\`\`\`\n${text.trim()}\n\`\`\`\n`);
}
const md = `# Third-party notices

v2tun includes the following software. Because sing-box and the sing libraries
are licensed under GPL-3.0-or-later, v2tun as a whole is distributed under the
GNU General Public License v3 (see LICENSE), and its source code is published.

Bundled binaries and assets (not Go modules):

| Component | License |
|---|---|
| wintun.dll (WireGuard LLC) | Wintun prebuilt binaries license: redistribution allowed unmodified, see https://www.wintun.net |
| libcronet.dll / libcronet.so (Chromium network stack, via sagernet/cronet-go) | BSD-3-Clause (Chromium) |
| Vazirmatn font (Saber Rastikerdar) | SIL Open Font License 1.1 |

Go modules compiled into v2tun (Windows and Linux; generated by tools/notices.js):

| Module | Version | License |
|---|---|---|
${rows.join("\n")}

## License texts

${texts.join("\n")}`;
fs.writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), md);
const unknown = rows.filter((r) => /UNKNOWN|see license/.test(r));
console.log(`${rows.length} modules, ${unknown.length} to check by hand`);
console.log(unknown.join("\n"));
const gpl = rows.filter((r) => /GPL-3/.test(r));
console.log("GPL-3.0 modules:\n" + gpl.join("\n"));
